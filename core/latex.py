"""Utilities for validating LaTeX formatting in model responses."""

from __future__ import annotations

import re


_COMMAND_PATTERN = re.compile(r"(?<!\\)\\[a-zA-Z]+")


def find_bare_latex_commands(content: str) -> list[str]:
    """Find LaTeX commands that appear outside supported math delimiters.

    Args:
        content: Markdown response generated by the assistant.

    Returns:
        Distinct command strings, such as ``\\quad``, outside math mode.
    """
    math_ranges = _math_ranges(content)
    commands: list[str] = []
    for match in _COMMAND_PATTERN.finditer(content):
        if not any(start <= match.start() < end for start, end in math_ranges):
            command = match.group()
            if command not in commands:
                commands.append(command)
    return commands


def _math_ranges(content: str) -> list[tuple[int, int]]:
    """Return character ranges delimited by supported LaTeX markers."""
    ranges: list[tuple[int, int]] = []
    index = 0
    while index < len(content):
        delimiter = _opening_delimiter(content, index)
        if delimiter is None:
            index += 1
            continue

        opening, closing = delimiter
        end = content.find(closing, index + len(opening))
        if end == -1:
            index += len(opening)
            continue
        ranges.append((index, end + len(closing)))
        index = end + len(closing)
    return ranges


def _opening_delimiter(content: str, index: int) -> tuple[str, str] | None:
    """Return a math delimiter that starts at the requested character index."""
    if content.startswith("\\[", index):
        return "\\[", "\\]"
    if content.startswith("\\(", index):
        return "\\(", "\\)"
    if content.startswith("$$", index):
        return "$$", "$$"
    if content[index] == "$" and not content.startswith("$$", index):
        return "$", "$"
    return None
