"""Persistent dense-vector index for long-term memory retrieval."""

from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
from typing import Any

from config import DATA_DIR


INDEX_SCHEMA_VERSION = 1
INDEX_DIR = DATA_DIR / "embeddings"


def _index_path(mode: str) -> Path:
    """Return the vector-index path for a conversation mode."""
    return INDEX_DIR / f"{mode}.json"


def fingerprint(content: str) -> str:
    """Return a stable fingerprint for a memory text."""
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def _default_index(mode: str, model_id: str = "") -> dict[str, Any]:
    """Create an empty vector-index record."""
    return {
        "version": INDEX_SCHEMA_VERSION,
        "mode": mode,
        "model_id": model_id,
        "entries": {},
    }


def load(mode: str, model_id: str) -> dict[str, Any]:
    """Load an index compatible with the requested embedding model.

    A model identifier change intentionally returns an empty index so vectors
    generated by a different model are never mixed with current vectors.

    Args:
        mode: Conversation mode.
        model_id: Stable identifier for the active embedding model.

    Returns:
        A valid vector-index record.
    """
    INDEX_DIR.mkdir(parents=True, exist_ok=True)
    path = _index_path(mode)
    if not path.exists():
        return _default_index(mode, model_id)

    try:
        with open(path, "r", encoding="utf-8") as file:
            raw = json.load(file)
    except (OSError, json.JSONDecodeError):
        return _default_index(mode, model_id)

    if not isinstance(raw, dict) or raw.get("model_id") != model_id:
        return _default_index(mode, model_id)

    entries = raw.get("entries")
    if not isinstance(entries, dict):
        return _default_index(mode, model_id)

    valid_entries: dict[str, dict[str, Any]] = {}
    for key, entry in entries.items():
        if not isinstance(key, str) or not isinstance(entry, dict):
            continue
        vector = entry.get("vector")
        if isinstance(vector, list) and all(isinstance(value, (int, float)) for value in vector):
            valid_entries[key] = {
                "content": entry.get("content", "") if isinstance(entry.get("content"), str) else "",
                "vector": [float(value) for value in vector],
                "created_at": entry.get("created_at", "") if isinstance(entry.get("created_at"), str) else "",
            }

    record = _default_index(mode, model_id)
    record["entries"] = valid_entries
    return record


def save(mode: str, index: dict[str, Any]) -> None:
    """Persist a vector-index record.

    Args:
        mode: Conversation mode.
        index: Validated index record.
    """
    INDEX_DIR.mkdir(parents=True, exist_ok=True)
    with open(_index_path(mode), "w", encoding="utf-8") as file:
        json.dump(index, file, ensure_ascii=False, indent=2)


def upsert(index: dict[str, Any], content: str, vector: list[float]) -> None:
    """Insert or replace the vector for one memory text.

    Args:
        index: Mutable vector-index record.
        content: Source memory text.
        vector: Dense embedding generated for the text.
    """
    index["entries"][fingerprint(content)] = {
        "content": content,
        "vector": vector,
        "created_at": datetime.now(timezone.utc).isoformat(),
    }


def remove_missing(index: dict[str, Any], contents: list[str]) -> None:
    """Remove index entries whose memory text no longer exists.

    Args:
        index: Mutable vector-index record.
        contents: Current memory texts for the mode.
    """
    expected_keys = {fingerprint(content) for content in contents}
    index["entries"] = {
        key: entry
        for key, entry in index["entries"].items()
        if key in expected_keys
    }
